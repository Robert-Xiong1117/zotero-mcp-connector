"""Write bridge: talks to the ZoteroMCP Bridge plugin inside Zotero (the local API on 23119 is read-only).

The plugin adds token-protected endpoints to Zotero's own HTTP server (127.0.0.1 only):
  GET /zmc/ping, POST /zmc/annotate, POST /zmc/find-pdf
The token is generated by the connector (Config.zmc_bridge_token) and pasted into the plugin's pref.
Every failure here comes back as a clear message and never affects the other MCP tools.
"""
import json
import os
import re
import urllib.error
import urllib.parse
import urllib.request

ZOTERO_URL = "http://127.0.0.1:23119"
_NOPROXY = urllib.request.build_opener(urllib.request.ProxyHandler({}))

MSG_OFFLINE = "Zotero 未运行（127.0.0.1:23119 无响应）。请先打开 Zotero。"
MSG_MISSING = ("Zotero 中未安装或未启用「ZoteroMCP Bridge」插件。请在 Zotero → 工具 → 插件 中安装 "
               "ZoteroMCP-Bridge-*.xpi（见 ZoteroMCP 控制面板），然后重启 Zotero。")
MSG_FORBIDDEN = ("桥接插件拒绝了请求（Token 不匹配）。请在 ZoteroMCP 控制面板复制桥接 Token，粘贴到 Zotero → 设置 → "
                 "高级 →「设置编辑器」中的 extensions.zmc-bridge.token。")
MSG_NO_TOKEN = "ZoteroMCP 尚未生成桥接 Token：请在控制面板点「启动 / 重启」后重试。"


class BridgeError(Exception):
    def __init__(self, message: str, state: str = "error"):
        super().__init__(message)
        self.state = state


def _base() -> str:
    return os.environ.get("ZMC_ZOTERO_URL", ZOTERO_URL).rstrip("/")


def _token(token=None) -> str:
    return token if token is not None else os.environ.get("ZMC_BRIDGE_TOKEN", "")


def request(method: str, path: str, data=None, token=None, timeout: float = 30.0) -> dict:
    tok = _token(token)
    if not tok:
        raise BridgeError(MSG_NO_TOKEN, "no-token")
    body = json.dumps(data or {}).encode("utf-8") if method == "POST" else None
    req = urllib.request.Request(_base() + path, data=body, method=method, headers={
        "X-ZMC-Token": tok, "Content-Type": "application/json", "Zotero-Allowed-Request": "1"})
    try:
        with _NOPROXY.open(req, timeout=timeout) as r:
            return json.loads(r.read().decode("utf-8") or "{}")
    except urllib.error.HTTPError as e:
        raw = e.read().decode("utf-8", "replace")
        try:
            detail = json.loads(raw).get("error", "")
        except ValueError:
            detail = None                       # Zotero's own plain-text reply: our endpoint does not exist
        if e.code == 404 and detail is None:
            raise BridgeError(MSG_MISSING, "missing") from None
        if e.code == 403:
            raise BridgeError(MSG_FORBIDDEN, "forbidden") from None
        raise BridgeError(f"桥接插件返回 HTTP {e.code}：{detail or raw[:200]}", "error") from None
    except (urllib.error.URLError, ConnectionError, TimeoutError, OSError) as e:
        if isinstance(e, TimeoutError) or "timed out" in str(e):
            raise BridgeError(f"Zotero 响应超时（{timeout:.0f} 秒）", "timeout") from None
        raise BridgeError(MSG_OFFLINE, "offline") from None


def ping(token=None, timeout: float = 3.0) -> dict:
    """{state: ok|offline|missing|forbidden|no-token|error|timeout, version?, message?}"""
    try:
        r = request("GET", "/zmc/ping", token=token, timeout=timeout)
        return {"state": "ok", "version": r.get("version", ""), "zotero": r.get("zotero", "")}
    except BridgeError as e:
        return {"state": e.state, "message": str(e)}


# ---------- attachments ----------
def _pdf_attachment(zot, item_key: str) -> dict:
    """Attachment data dict (with 'key') of the item's PDF, or the item itself if it is a PDF attachment."""
    item = zot.item(item_key)
    data = item.get("data", {})
    if data.get("itemType") == "attachment":
        if data.get("contentType") != "application/pdf":
            raise BridgeError(f"{item_key} 是附件，但不是 PDF（{data.get('contentType') or '未知类型'}）")
        return data
    for child in zot.children(item_key):
        d = child.get("data", {})
        if d.get("itemType") == "attachment" and d.get("contentType") == "application/pdf" \
                and d.get("linkMode") != "linked_url":
            return d
    raise BridgeError(f"条目 {item_key} 没有 PDF 附件。可先调用 zotero_find_pdf 查找可用 PDF。", "no-pdf")


def local_pdf(att: dict) -> str:
    """Filesystem path of the attachment, as Zotero itself reports it (works for any data directory,
    linked files and relative base paths); a linked file's absolute path is the fallback."""
    try:
        url = f"{_base()}/api/users/0/items/{att['key']}/file/view/url"
        with _NOPROXY.open(url, timeout=10) as r:
            file_url = r.read().decode("utf-8").strip()
        if file_url.startswith("file:"):
            p = urllib.request.url2pathname(urllib.parse.urlparse(file_url).path)
            if os.name == "nt" and re.match(r"^\\[A-Za-z]:", p):
                p = p[1:]
            if os.path.exists(p):
                return p
    except Exception:
        pass
    path = att.get("path") or ""
    if att.get("linkMode") == "linked_file" and os.path.isabs(path) and os.path.exists(path):
        return path
    raise BridgeError("找不到 PDF 文件（附件文件不在本机，可能尚未同步）。请在 Zotero 中打开该 PDF 让其下载后重试。", "no-file")


# ---------- tools ----------
def highlight_quote(item_key: str, quote: str, comment: str = "", color: str = "#ffd400", zot=None) -> dict:
    from . import pdfquote
    if not re.fullmatch(r"#[0-9a-fA-F]{6}", color or ""):
        return {"ok": False, "error": "color 必须是 #RRGGBB 格式，例如 #ffd400"}
    try:
        info = ping(timeout=5)
        if info["state"] != "ok":
            return {"ok": False, "error": info["message"]}
        if zot is None:
            from zotero_mcp.client import get_zotero_client
            zot = get_zotero_client()
        att = _pdf_attachment(zot, item_key)
        hit, cands = pdfquote.locate(local_pdf(att), quote)
        if hit is None:
            return {"ok": False, "written": False, "error": "PDF 中找不到这句原文（精确与规范化匹配均失败），未写入任何批注。",
                    "candidates": cands,
                    "hint": "如果某个候选就是要找的句子，请用候选的原文（逐字）再调用一次。"}
        position = {"pageIndex": hit.page_index, "rects": hit.rects}
        if hit.next_page_rects:
            position["nextPageRects"] = hit.next_page_rects
        r = request("POST", "/zmc/annotate", {"attachmentKey": att["key"], "annotation": {
            "type": "highlight", "text": quote.strip(), "comment": comment, "color": color.lower(),
            "pageLabel": hit.page_label, "sortIndex": hit.sort_index, "position": position}})
        out = {"ok": True, "written": True, "annotation_key": r.get("key"), "attachment_key": att["key"],
               "page": hit.page_label, "page_index": hit.page_index, "match": hit.method,
               "lines": len(hit.rects) + len(hit.next_page_rects)}
        if hit.occurrences > 1:
            out["note"] = f"原文在 PDF 中出现 {hit.occurrences} 次，已高亮第一次出现的位置。"
        return out
    except BridgeError as e:
        return {"ok": False, "error": str(e)}
    except ValueError as e:
        return {"ok": False, "error": str(e)}
    except Exception as e:
        return {"ok": False, "error": f"{type(e).__name__}: {e}"}


def find_pdf(item_key: str) -> dict:
    try:
        r = request("POST", "/zmc/find-pdf", {"itemKey": item_key}, timeout=180)
    except BridgeError as e:
        return {"ok": False, "error": str(e)}
    if not r.get("found"):
        return {"ok": True, "found": False,
                "message": "Zotero 没有找到可用的开放获取 PDF（按 DOI/URL 及 Unpaywall 等解析器）。可手动下载后拖入 Zotero。"}
    return {"ok": True, "found": True, "already_had_pdf": bool(r.get("already")),
            "attachment_key": r.get("attachmentKey"), "filename": r.get("filename")}


def register(mcp) -> None:
    """Attach the two bridge tools to the zotero-mcp-lite server."""
    mcp.tool(name="zotero_highlight_quote", description=(
        "Highlight an exact sentence in an item's PDF inside Zotero (writes a highlight annotation). "
        "Pass the quote verbatim as it appears in the paper (copy from zotero_get_item_fulltext). "
        "Matching is exact first, then whitespace/hyphenation/line-break tolerant; it never writes a fuzzy match — "
        "if nothing matches it returns the closest candidate sentences instead. Returns page, match type and "
        "annotation key. Requires the ZoteroMCP Bridge plugin in Zotero."))(_highlight_tool)
    mcp.tool(name="zotero_find_pdf", description=(
        "Run Zotero's 'Find Available PDF' for an item (open-access lookup by DOI/URL) and attach the PDF if found. "
        "Use before reading or highlighting an item that has no PDF. Requires the ZoteroMCP Bridge plugin."))(find_pdf)


def _highlight_tool(item_key: str, quote: str, comment: str = "", color: str = "#ffd400") -> dict:
    return highlight_quote(item_key, quote, comment, color)
